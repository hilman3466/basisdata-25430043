-- 6. Ringkasan jumlah baris per tabel ------------------------------
SELECT 'pelanggan' AS tabel, COUNT(*) AS jumlah FROM pelanggan
UNION ALL SELECT 'petugas', COUNT(*) FROM petugas
UNION ALL SELECT 'barang', COUNT(*) FROM barang
UNION ALL SELECT 'pemasok', COUNT(*) FROM pemasok
UNION ALL SELECT 'program_hadiah', COUNT(*) FROM program_hadiah
UNION ALL SELECT 'program_hadiah_barang', COUNT(*) FROM program_hadiah_barang
UNION ALL SELECT 'pesanan', COUNT(*) FROM pesanan
UNION ALL SELECT 'detail_pesanan', COUNT(*) FROM detail_pesanan
UNION ALL SELECT 'riwayat_perubahan_pesanan', COUNT(*) FROM riwayat_perubahan_pesanan
UNION ALL SELECT 'penjualan', COUNT(*) FROM penjualan
UNION ALL SELECT 'detail_penjualan', COUNT(*) FROM detail_penjualan
UNION ALL SELECT 'pesanan_pembelian', COUNT(*) FROM pesanan_pembelian
UNION ALL SELECT 'detail_pesanan_pembelian', COUNT(*) FROM detail_pesanan_pembelian
UNION ALL SELECT 'penerimaan_barang', COUNT(*) FROM penerimaan_barang
UNION ALL SELECT 'detail_penerimaan', COUNT(*) FROM detail_penerimaan
UNION ALL SELECT 'tagihan_pemasok', COUNT(*) FROM tagihan_pemasok
UNION ALL SELECT 'pembayaran_tagihan', COUNT(*) FROM pembayaran_tagihan
UNION ALL SELECT 'klaim_hadiah', COUNT(*) FROM klaim_hadiah;
